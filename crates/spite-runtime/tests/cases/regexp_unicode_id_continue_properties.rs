#[test]
fn unicode_id_continue_property_results_snapshot() {
    let boundary_samples = unicode_samples::from_ranges(BOUNDARY_SAMPLES);
    let mut rows = String::new();
    for body in [
        r"\p{ID_Continue}",
        r"\P{IDC}",
        r"[^\p{IDC}]",
        r"[\p{IDC}K]",
        r"[\P{ID_Continue}K]",
        r"^(?<x>[\p{IDC}K])$",
        r"(?<x>\P{ID_Continue})",
    ] {
        let pattern = JsString::from(body);
        for flags in ["dug", "diug", "divg", "divmy"] {
            for input in [
                boundary_samples.as_str(),
                "X\r\n\u{41}\u{2028}\u{42}\u{2029}",
                "\u{ff10}\u{ff26}",
                "",
            ] {
                let input = JsString::from(input);
                for start in last_index_cases(input.len()) {
                    let script = format!(
                        r#"
                            let r = new RegExp({pattern:?}, '{flags}');
                            r.lastIndex = {start};
                            let m = r.exec({input:?});
                            JSON.stringify(m === null ? {{
                                match: null,
                                lastIndex: r.lastIndex
                            }} : {{
                                matches: [...m],
                                index: m.index,
                                input: m.input,
                                groups: m.groups,
                                indices: m.indices,
                                indexGroups: m.indices.groups,
                                lastIndex: r.lastIndex,
                                source: r.source
                            }})
                        "#
                    );
                    let Value::String(result) = Realm::default().eval(&script).unwrap() else {
                        panic!("{script}")
                    };
                    writeln!(
                        rows,
                        "{pattern:?} flags={flags:?} input={input:?} lastIndex={start} => {result}",
                        result = result.to_utf8().expect("JSON output must be valid UTF-8"),
                    )
                    .unwrap();
                }
            }
        }
    }
    insta::assert_snapshot!(rows);
}

#[test]
fn unicode_id_continue_properties_aliases_complements_and_unions() {
    for mode in ["u", "v"] {
        assert_true(&format!(
            r#"
                let p = /^\p{{IDC}}$/i{mode},
                    q = /^\p{{ID_Continue}}$/i{mode},
                    n = /^\P{{IDC}}$/i{mode};
                'AſK\u200C\uFEFF'.split('').every(c => p.test(c) === q.test(c) && n.test(c) !== p.test(c))
            "#
        ));
    }

    for mode in ["u", "v"] {
        assert_true(&format!(
            r#"
                let a = /\p{{ID_Continue}}/{mode},
                    b = /\p{{IDC}}/i{mode},
                    n = /\P{{IDC}}/i{mode};
                a.test('\u0041') && a.test('\u0042') && b.test('\u0041') && !a.test('\u0021') && b.test(
                    '\u005f') && b.test('ſ') && b.test('K') && !n.test('\u0041') && n.test(
                    '\uDB40\uDC01') && n.test('\uD800') && n.test('\uFEFF')
            "#
        ));
        assert_true(&format!(
            r#"
                let p = /\p{{ID_Continue}}/{mode},
                    s = /\s/{mode};
                p.test('\u0041') && p.test('\u0042') && !s.test('\u0041') && !s.test('\u0042') && !p.test(
                    '\uFEFF') && s.test('\uFEFF')
            "#
        ));
        assert_true(&format!(
            r#"
                let a = /[\p{{IDC}}K]/i{mode},
                    b = /[^\P{{ID_Continue}}K]/i{mode},
                    c = /[\p{{IDC}}\P{{ID_Continue}}]/{mode};
                a.test('K') && a.test('k') && a.test('\u0041') && a.test('ſ') && b.test('\u0042') && !b.test(
                    'K') && c.test('\uDB40\uDC01') && c.test('A') && c.test('\uD800')
            "#
        ));
        assert_true(&format!(
            r#"
                let a = /^\p{{IDC}}$/{mode},
                    b = /^\P{{IDC}}$/{mode};
                a.test('\u0041') && !a.test('\u0042\n') && !a.test('') && !a.test('\n') && b.test(
                    '\uDB40\uDC01') && !b.test('AA')
            "#
        ));
    }
}

#[test]
