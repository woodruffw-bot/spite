#[test]
fn unicode_grapheme_base_property_results_snapshot() {
    let boundary_samples = unicode_samples::from_ranges(BOUNDARY_SAMPLES);
    let mut rows = String::new();
    for body in [
        r"\p{Grapheme_Base}",
        r"\P{Gr_Base}",
        r"[^\p{Gr_Base}]",
        r"[\p{Gr_Base}K]",
        r"[\P{Grapheme_Base}K]",
        r"^(?<x>[\p{Gr_Base}K])$",
        r"(?<x>\P{Grapheme_Base})",
    ] {
        let pattern = JsString::from(body);
        for flags in ["dug", "diug", "divg", "divmy"] {
            for input in [
                boundary_samples.as_str(),
                "X\r\n\u{41}\u{2028}\u{42}\u{2029}",
                "\u{ff10}\u{ff26}",
                "",
            ] {
                let input = JsString::from(input);
                for start in [0, 1, 2, input.len(), input.len() + 1] {
                    let script = format!(
                        r#"
                            let r = new RegExp({pattern:?}, '{flags}');
                            r.lastIndex = {start};
                            let m = r.exec({input:?});
                            JSON.stringify(m === null ? {{
                                match: null,
                                lastIndex: r.lastIndex
                            }} : {{
                                matches: [...m],
                                index: m.index,
                                input: m.input,
                                groups: m.groups,
                                indices: m.indices,
                                indexGroups: m.indices.groups,
                                lastIndex: r.lastIndex,
                                source: r.source
                            }})
                        "#
                    );
                    let Value::String(result) = Realm::default().eval(&script).unwrap() else {
                        panic!("{script}")
                    };
                    writeln!(
                        rows,
                        "{pattern:?} flags={flags:?} input={input:?} lastIndex={start} => {result}",
                        result = result.to_utf8().expect("JSON output must be valid UTF-8"),
                    )
                    .unwrap();
                }
            }
        }
    }
    insta::assert_snapshot!(rows);
}

#[test]
fn unicode_grapheme_base_properties_aliases_complements_and_unions() {
    for mode in ["u", "v"] {
        assert_true(&format!(
            r#"
                let p = /^\p{{Gr_Base}}$/i{mode},
                    n = /^\P{{Gr_Base}}$/i{mode};
                '\u0345\u0399\u03B9\u1FBE'.split('').every(c => p.test(c) && n.test(c) === (
                    '{mode}' ===
                    'u'))
            "#
        ));
        assert_true(&format!(
            r#"
                let p = /[\p{{Gr_Base}}K]/i{mode},
                    n = /[\P{{Gr_Base}}K]/i{mode},
                    x = /[^\P{{Gr_Base}}K]/i{mode};
                p.test('K') && n.test('K') && !x.test('K') && '\u0345\u0399\u03B9\u1FBE'.split('').every(c => p
                    .test(c) && n.test(c) === ('{mode}' === 'u') && x.test(c) === (
                        '{mode}' === 'v'))
            "#
        ));
    }

    for mode in ["u", "v"] {
        assert_true(&format!(
            r#"
                let a = /\p{{Grapheme_Base}}/{mode},
                    b = /\p{{Gr_Base}}/i{mode},
                    n = /\P{{Gr_Base}}/i{mode};
                a.test('\u0041') && a.test('\u0042') && b.test('\u0041') && !a.test('\u200D') && b.test(
                    '\u005f') && b.test('ſ') && b.test('K') && !n.test('\u0041') && n.test(
                    '\uDB40\uDC01') && n.test('\uD800') && n.test('\uFEFF')
            "#
        ));
        assert_true(&format!(
            r#"
                let p = /\p{{Grapheme_Base}}/{mode},
                    s = /\s/{mode};
                p.test('\u0041') && p.test('\u0042') && !s.test('\u0041') && !s.test('\u0042') && !p.test(
                    '\uFEFF') && s.test('\uFEFF')
            "#
        ));
        assert_true(&format!(
            r#"
                let a = /[\p{{Gr_Base}}K]/i{mode},
                    b = /[^\P{{Grapheme_Base}}K]/i{mode},
                    c = /[\p{{Gr_Base}}\P{{Grapheme_Base}}]/{mode};
                a.test('K') && a.test('k') && a.test('\u0041') && a.test('ſ') && b.test('\u0042') && !b.test(
                    'K') && c.test('\uDB40\uDC01') && c.test('A') && c.test('\uD800')
            "#
        ));
        assert_true(&format!(
            r#"
                let a = /^\p{{Gr_Base}}$/{mode},
                    b = /^\P{{Gr_Base}}$/{mode};
                a.test('\u0041') && !a.test('\u0042\n') && !a.test('') && !a.test('\n') && b.test(
                    '\uDB40\uDC01') && !b.test('AA')
            "#
        ));
    }
}

#[test]
