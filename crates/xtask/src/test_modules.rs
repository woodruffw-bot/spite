//! Keep grouped integration targets complete without a custom test runner.

use crate::Result;
use crate::invalid;
use std::fs;
use std::path::Path;

pub(crate) fn update(root: &Path, check: bool) -> Result<()> {
    for (package, subdirectory, prefix) in [
        ("spite-parser", "", ""),
        ("spite-runtime", "cases", "mod common;\n\n"),
    ] {
        let tests = root.join("crates").join(package).join("tests");
        let mut names = Vec::new();
        for entry in fs::read_dir(tests.join(subdirectory))? {
            let entry = entry?;
            let path = entry.path();
            if path.extension().is_some_and(|extension| extension == "rs")
                && path.file_stem().is_some_and(|stem| stem != "integration")
            {
                if !entry.file_type()?.is_file() {
                    return Err(invalid(format!(
                        "case must be a regular file: {}",
                        path.display()
                    ))
                    .into());
                }
                let name = path
                    .file_stem()
                    .and_then(|name| name.to_str())
                    .ok_or_else(|| invalid("non-UTF-8 case filename"))?;
                if !name
                    .bytes()
                    .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_')
                    || !name.starts_with(|character: char| character.is_ascii_lowercase())
                {
                    return Err(invalid(format!(
                        "case filename must be a Rust module name: {name}"
                    ))
                    .into());
                }
                names.push(name.to_owned());
            }
        }
        names.sort();
        if names.is_empty() {
            return Err(invalid(format!("{package} case inventory is empty")).into());
        }
        let mut source = String::from(
            "//! Integration cases. Generated by cargo xtask generate test-modules.\n\n",
        );
        source.push_str(prefix);
        for name in names {
            if !subdirectory.is_empty() {
                source.push_str(&format!("#[path = \"{subdirectory}/{name}.rs\"]\n"));
            }
            source.push_str(&format!("mod {name};\n"));
        }
        let destination = tests.join("integration.rs");
        if check {
            if fs::read_to_string(&destination)? != source {
                return Err(invalid(format!(
                    "{} is stale; run cargo xtask generate test-modules",
                    destination.display()
                ))
                .into());
            }
        } else {
            fs::write(destination, source)?;
        }
    }
    Ok(())
}
