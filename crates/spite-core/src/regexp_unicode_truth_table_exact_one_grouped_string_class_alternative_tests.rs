#[test]
fn truth_table_exact_grouped_alternatives_match_independent_branch_priority_and_endpoint_oracle() {
    use crate::RegExpUnicodeTruthTableExactOneGroupedStringClassAlternativeMatcher as P;
    let profiles = [
        ("^", r"\b", 1u8, 4u8),
        ("$", r"\b", 2, 4),
        ("^", "$", 1, 2),
        (r"\b^", "$", 5, 2),
        (r"\B^", r"\b$", 9, 6),
        ("^", r"\B", 1, 8),
        ("$", r"\B", 2, 8),
        (r"\b\B", r"\b\B", 12, 12),
    ];
    for (k, (left, right, lf, rf)) in profiles.into_iter().enumerate() {
        let (al, ar, alf, arf) = profiles[(k + 3) % profiles.len()];
        let (el, er, elf, erf) = profiles[(k + 5) % profiles.len()];
        let (tl, tr, tlf, trf) = profiles[(k + 7) % profiles.len()];
        for (class, nullable, scalar, never) in [
            (r"[\q{a|ab}]", false, false, false),
            (r"[\q{|a|ab}]", true, false, false),
            (r"[\p{Any}\q{|ab}]", true, true, false),
            (r"[\q{ab}&&\q{cd}]", false, false, true),
        ] {
            for class_first in [false, true] {
                for count in ["", "{1}", "{0001,0001}?"] {
                    for outside in ["", "{2,3}?", "{999999999999999999999999}", "?", "{0,2}?"] {
                        let a = format!(
                            "(({left})|({right})){outside}({class}){count}(({al})|({ar})){outside}"
                        );
                        let b = format!("(({el})|({er})){outside}()(({tl})|({tr})){outside}");
                        let source = if class_first {
                            format!("{a}|{b}")
                        } else {
                            format!("{b}|{a}")
                        };
                        let source = format!("((?:({source}){{1}}){{1,1}}){{1}}?");
                        for (i, m) in [(false, false), (true, false), (false, true), (true, true)] {
                            let plan = P::compile_with_work(
                                &JsString::from(source.as_str()),
                                i,
                                m,
                                |_| Ok::<(), ()>(()),
                            )
                            .unwrap()
                            .unwrap_or_else(|| panic!("declined {source}"));
                            assert_eq!(plan.capture_count(), 16);
                            for text in [
                                "",
                                "a",
                                "ab",
                                "aba",
                                "!ab!",
                                "AB",
                                "ſab!",
                                "😀a",
                                "a\n",
                                "\u{2028}ab\u{2029}",
                            ] {
                                let input = JsString::from(text);
                                let u = input.code_units();
                                let skip = matches!(outside, "?" | "{0,2}?");
                                let predicate = |at: usize, flags: u8| {
                                    let word = |p: Option<&u16>| {
                                        p.is_some_and(|p| {
                                            matches!(*p,0x30..=0x39|0x41..=0x5a|0x5f|0x61..=0x7a)
                                                || (i && matches!(*p, 0x17f | 0x212a))
                                        })
                                    };
                                    let boundary = word(at.checked_sub(1).and_then(|p| u.get(p)))
                                        != word(u.get(at));
                                    (flags & 1 == 0
                                        || at == 0
                                        || (m && matches!(u[at - 1], 0xa | 0xd | 0x2028 | 0x2029)))
                                        && (flags & 2 == 0
                                            || at == u.len()
                                            || (m && matches!(u[at], 0xa | 0xd | 0x2028 | 0x2029)))
                                        && (flags & 4 == 0 || boundary)
                                        && (flags & 8 == 0 || !boundary)
                                };
                                for requested in 0..=u.len() + 1 {
                                    for sticky in [false, true] {
                                        let mut at = requested;
                                        if at > 0
                                            && at < u.len()
                                            && (0xdc00..=0xdfff).contains(&u[at])
                                            && (0xd800..=0xdbff).contains(&u[at - 1])
                                        {
                                            at -= 1;
                                        }
                                        let mut expected = None;
                                        while at <= u.len() {
                                            let empty =
                                                (skip || predicate(at, elf) || predicate(at, erf))
                                                    && (skip
                                                        || predicate(at, tlf)
                                                        || predicate(at, trf));
                                            let fold = |p: Option<&u16>| {
                                                p.copied().map(|p| {
                                                    if i && (0x41..=0x5a).contains(&p) {
                                                        p + 32
                                                    } else {
                                                        p
                                                    }
                                                })
                                            };
                                            let astral = u
                                                .get(at)
                                                .is_some_and(|p| (0xd800..=0xdbff).contains(p))
                                                && u.get(at + 1)
                                                    .is_some_and(|p| (0xdc00..=0xdfff).contains(p));
                                            let mut class_end = None;
                                            if skip || predicate(at, lf) || predicate(at, rf) {
                                                for width in [2, 1, 0] {
                                                    let member = !never
                                                        && match width {
                                                            2 => {
                                                                (fold(u.get(at)) == Some(0x61)
                                                                    && fold(u.get(at + 1))
                                                                        == Some(0x62))
                                                                    || (scalar && astral)
                                                            }
                                                            1 => {
                                                                fold(u.get(at)) == Some(0x61)
                                                                    || (scalar
                                                                        && at < u.len()
                                                                        && !astral)
                                                            }
                                                            _ => nullable,
                                                        };
                                                    if member
                                                        && (skip
                                                            || predicate(at + width, alf)
                                                            || predicate(at + width, arf))
                                                    {
                                                        class_end = Some(at + width);
                                                        break;
                                                    }
                                                }
                                            }
                                            let chosen = if class_first {
                                                class_end
                                                    .map(|end| (end, true))
                                                    .or_else(|| empty.then_some((at, false)))
                                            } else {
                                                empty
                                                    .then_some((at, false))
                                                    .or_else(|| class_end.map(|end| (end, true)))
                                            };
                                            if let Some((end, selected)) = chosen {
                                                expected = Some((at..end, selected));
                                                break;
                                            }
                                            if sticky || at == u.len() {
                                                break;
                                            }
                                            at += if astral { 2 } else { 1 };
                                        }
                                        let found = plan
                                            .find_with_captures_and_work(
                                                &input,
                                                requested,
                                                sticky,
                                                |_| Ok::<(), ()>(()),
                                            )
                                            .unwrap();
                                        assert_eq!(
                                            found.as_ref().map(|f| (
                                                f.repeated.range.clone(),
                                                f.repeated.class_selected
                                            )),
                                            expected,
                                            "{source}, {text:?}, {requested}, {sticky}, {i}, {m}"
                                        );
                                        if let Some(f) = found {
                                            let selected = f.repeated.class_selected;
                                            let range = f.repeated.range.clone();
                                            assert_eq!(
                                                f.repeated.last_iteration,
                                                Some(range.clone())
                                            );
                                            let offset =
                                                if selected == class_first { 2 } else { 9 };
                                            let mut want = vec![None; 16];
                                            want[0] = Some(range.clone());
                                            want[1] = Some(range.clone());
                                            want[offset + 3] = Some(range.clone());
                                            if !skip {
                                                let (bl, br, cl, cr) = if selected {
                                                    (lf, rf, alf, arf)
                                                } else {
                                                    (elf, erf, tlf, trf)
                                                };
                                                assert!(
                                                    predicate(range.start, bl)
                                                        || predicate(range.start, br)
                                                );
                                                assert!(
                                                    predicate(range.end, cl)
                                                        || predicate(range.end, cr)
                                                );
                                                want[offset] = Some(range.start..range.start);
                                                want[offset
                                                    + if predicate(range.start, bl) {
                                                        1
                                                    } else {
                                                        2
                                                    }] = Some(range.start..range.start);
                                                want[offset + 4] = Some(range.end..range.end);
                                                want[offset
                                                    + if predicate(range.end, cl) {
                                                        5
                                                    } else {
                                                        6
                                                    }] = Some(range.end..range.end);
                                            }
                                            assert_eq!(
                                                (0..16)
                                                    .map(|n| plan.capture_range(n, &f))
                                                    .collect::<Vec<_>>(),
                                                want,
                                                "{source}, {text:?}, {requested}"
                                            );
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

