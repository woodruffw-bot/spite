#[test]
fn truth_table_zero_count_root_alternatives_match_independent_progress_and_capture_oracle() {
    use crate::RegExpUnicodeTruthTableZeroCountRootStringClassAlternativeMatcher as P;
    let profiles = [
        ("^", r"\b", 1u8, 4u8),
        ("$", r"\b", 2, 4),
        ("^", "$", 1, 2),
        (r"\b^", "$", 5, 2),
        (r"\B^", r"\b$", 9, 6),
        ("^", r"\B", 1, 8),
        ("$", r"\B", 2, 8),
        (r"\b\B", r"\b\B", 12, 12),
    ];
    for (k, (left, right, lf, _rf)) in profiles.into_iter().enumerate() {
        let (al, ar, alf, _arf) = profiles[(k + 3) % profiles.len()];
        let (el, er, _, _) = profiles[(k + 5) % profiles.len()];
        let (tl, tr, _, _) = profiles[(k + 7) % profiles.len()];
        for (class, _scalar, _never) in [
            (r"[\q{a|ab}]", false, false),
            (r"[\q{|a|ab}]", false, false),
            (r"[\p{Any}\q{|ab}]", true, false),
            (r"[\q{ab}&&\q{cd}]", false, true),
        ] {
            for class_first in [false, true] {
                for body_count in ["", "{1}", "{0001,0001}?"] {
                    for outside in ["", "{2,3}?", "{999999999999999999999999}", "?", "{0,2}?"] {
                        for (q, greedy) in [
                            ("{0}", false),
                            ("{0,0}?", false),
                            ("{0000,0000}", false),
                            ("{0000}?", false),
                        ] {
                            let a = format!(
                                "(({left})|({right})){outside}({class}){body_count}(({al})|({ar})){outside}"
                            );
                            let b = format!("(({el})|({er})){outside}()(({tl})|({tr})){outside}");
                            let source = if class_first {
                                format!("({a}|{b}){q}")
                            } else {
                                format!("({b}|{a}){q}")
                            };

                            let (cb, ca, cbf, caf) = [
                                ("^", "$", 1u8, 2u8),
                                (r"\b", r"\B", 4, 8),
                                ("", "$", 0, 2),
                                ("$", "^", 2, 1),
                                (r"\b\B", "", 12, 0),
                                (r"^\b", r"\B$", 5, 10),
                                (r"\B", "", 8, 0),
                                ("", r"\b", 0, 4),
                            ][k];

                            let (ol, orr, olf, orf) = profiles[(k + 2) % profiles.len()];
                            let (pl, pr, plf, prf) = profiles[(k + 6) % profiles.len()];
                            let source = format!(
                                "{cb}(({ol})|({orr})){outside}()((?:{source})){{1}}()(({pl})|({pr})){outside}{ca}"
                            );

                            for (i, m) in
                                [(false, false), (true, false), (false, true), (true, true)]
                            {
                                let plan = P::compile_with_work(
                                    &JsString::from(source.as_str()),
                                    i,
                                    m,
                                    |_| Ok::<(), ()>(()),
                                )
                                .unwrap()
                                .unwrap_or_else(|| panic!("declined {source}"));
                                assert_eq!(plan.capture_count(), 24);
                                for text in [
                                    "",
                                    "a",
                                    "ab",
                                    "aba",
                                    "!ab!",
                                    "AB",
                                    "ſab!",
                                    "😀a",
                                    "a\n",
                                    "\u{2028}ab\u{2029}",
                                ] {
                                    let input = JsString::from(text);
                                    let u = input.code_units();
                                    let skip = matches!(outside, "?" | "{0,2}?");
                                    let predicate = |at: usize, flags: u8| {
                                        let word = |p: Option<&u16>| {
                                            p.is_some_and(|p|matches!(*p,0x30..=0x39|0x41..=0x5a|0x5f|0x61..=0x7a)||(i&&matches!(*p,0x17f|0x212a)))
                                        };
                                        let boundary =
                                            word(at.checked_sub(1).and_then(|p| u.get(p)))
                                                != word(u.get(at));
                                        (flags & 1 == 0
                                            || at == 0
                                            || (m
                                                && matches!(
                                                    u[at - 1],
                                                    0xa | 0xd | 0x2028 | 0x2029
                                                )))
                                            && (flags & 2 == 0
                                                || at == u.len()
                                                || (m
                                                    && matches!(
                                                        u[at],
                                                        0xa | 0xd | 0x2028 | 0x2029
                                                    )))
                                            && (flags & 4 == 0 || boundary)
                                            && (flags & 8 == 0 || !boundary)
                                    };
                                    for requested in 0..=u.len() + 1 {
                                        for sticky in [false, true] {
                                            let mut at = requested;
                                            if at > 0
                                                && at < u.len()
                                                && (0xdc00..=0xdfff).contains(&u[at])
                                                && (0xd800..=0xdbff).contains(&u[at - 1])
                                            {
                                                at -= 1;
                                            }

                                            let mut expected = None;
                                            if at <= u.len() {
                                                let mut begin = at;
                                                loop {
                                                    let zero = predicate(begin, cbf)
                                                        && predicate(begin, caf)
                                                        && (skip
                                                            || predicate(begin, olf)
                                                            || predicate(begin, orf))
                                                        && (skip
                                                            || predicate(begin, plf)
                                                            || predicate(begin, prf));
                                                    let consuming: Option<std::ops::Range<usize>> =
                                                        None;
                                                    expected = if greedy {
                                                        consuming.or_else(|| {
                                                            zero.then_some(begin..begin)
                                                        })
                                                    } else {
                                                        zero.then_some(begin..begin).or(consuming)
                                                    };
                                                    if expected.is_some()
                                                        || sticky
                                                        || begin == u.len()
                                                    {
                                                        break;
                                                    }
                                                    let pair = (0xd800..=0xdbff)
                                                        .contains(&u[begin])
                                                        && u.get(begin + 1).is_some_and(|p| {
                                                            (0xdc00..=0xdfff).contains(p)
                                                        });
                                                    begin += if pair { 2 } else { 1 };
                                                }
                                            }
                                            let found = plan
                                                .find_with_captures_and_work(
                                                    &input,
                                                    requested,
                                                    sticky,
                                                    |_| Ok::<(), ()>(()),
                                                )
                                                .unwrap();
                                            assert_eq!(
                                                found.as_ref().map(|f| f.repeated.range.clone()),
                                                expected,
                                                "{source}, {text:?}, {requested}, {sticky}, {i}, {m}"
                                            );
                                            if let Some(f) = found {
                                                let range = f.repeated.range.clone();
                                                let selected = range.start != range.end;
                                                assert_eq!(f.repeated.class_selected, selected);
                                                assert_eq!(
                                                    f.repeated.last_iteration,
                                                    selected.then(|| range.clone())
                                                );
                                                let mut want = vec![None; 15];
                                                if selected {
                                                    want[0] = Some(range.clone());
                                                    let offset = if class_first { 1 } else { 8 };
                                                    want[offset + 3] = Some(range.clone());
                                                    if !skip {
                                                        want[offset] =
                                                            Some(range.start..range.start);
                                                        want[offset
                                                            + if predicate(range.start, lf) {
                                                                1
                                                            } else {
                                                                2
                                                            }] = Some(range.start..range.start);
                                                        want[offset + 4] =
                                                            Some(range.end..range.end);
                                                        want[offset
                                                            + if predicate(range.end, alf) {
                                                                5
                                                            } else {
                                                                6
                                                            }] = Some(range.end..range.end);
                                                    }
                                                }

                                                let mut all = vec![None; 24];
                                                all[3] = Some(range.start..range.start);
                                                all[4] = Some(range.clone());
                                                all[20] = Some(range.end..range.end);
                                                all[5..20].clone_from_slice(&want);
                                                if !skip {
                                                    all[0] = Some(range.start..range.start);
                                                    all[if predicate(range.start, olf) {
                                                        1
                                                    } else {
                                                        2
                                                    }] = Some(range.start..range.start);
                                                    all[21] = Some(range.end..range.end);
                                                    all[if predicate(range.end, plf) {
                                                        22
                                                    } else {
                                                        23
                                                    }] = Some(range.end..range.end);
                                                }
                                                assert_eq!(
                                                    (0..24)
                                                        .map(|n| plan.capture_range(n, &f))
                                                        .collect::<Vec<_>>(),
                                                    all,
                                                    "{source}, {text:?}, {requested}"
                                                );
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

