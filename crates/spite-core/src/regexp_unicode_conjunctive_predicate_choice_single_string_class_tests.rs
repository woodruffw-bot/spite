#[test]
fn conjunctive_predicate_choice_single_classes_match_independent_endpoint_and_repeat_continuations()
{
    use crate::RegExpUnicodeConjunctivePredicateChoiceSingleStringClassCaptureMatcher as P;
    // Flags are independent test predicates: start, end, word, nonword.
    let profiles = [
        (r"\b", r"\b", 4, 4),
        (r"\B", r"\b\B", 8, 12),
        (r"\b^", "^", 5, 1),
        (r"\B^", "^", 9, 1),
        (r"\b$", "$", 6, 2),
        (r"\B$", "$", 10, 2),
        (r"\b^$", "^$", 7, 3),
        (r"\b\B", r"\b\B", 12, 12),
    ];
    struct Ref<'a> {
        u: &'a [u16],
        i: bool,
        m: bool,
        minimum: usize,
        maximum: usize,
        lazy: bool,
        nullable: bool,
        after: [u8; 2],
        skip: bool,
    }
    impl Ref<'_> {
        fn predicate(&self, at: usize, flags: u8) -> bool {
            let u = self.u;
            let word = |p: Option<&u16>| {
                p.is_some_and(|p| {
                    matches!(*p,0x30..=0x39|0x41..=0x5a|0x5f|0x61..=0x7a)
                        || (self.i && matches!(*p, 0x17f | 0x212a))
                })
            };
            let boundary = word(at.checked_sub(1).and_then(|p| u.get(p))) != word(u.get(at));
            (flags & 1 == 0
                || at == 0
                || (self.m && matches!(u[at - 1], 0x0a | 0x0d | 0x2028 | 0x2029)))
                && (flags & 2 == 0
                    || at == u.len()
                    || (self.m && matches!(u[at], 0x0a | 0x0d | 0x2028 | 0x2029)))
                && (flags & 4 == 0 || boundary)
                && (flags & 8 == 0 || !boundary)
        }
        fn end(&self, at: usize) -> bool {
            self.skip || self.after.iter().any(|f| self.predicate(at, *f))
        }
        fn visit(
            &self,
            at: usize,
            count: usize,
            last: Option<std::ops::Range<usize>>,
        ) -> Option<(usize, Option<std::ops::Range<usize>>)> {
            if self.lazy && count >= self.minimum && self.end(at) {
                return Some((at, last));
            }
            if count < self.maximum {
                let fold = |p: Option<&u16>| {
                    p.copied().map(|p| {
                        if self.i && (0x41..=0x5a).contains(&p) {
                            p + 32
                        } else {
                            p
                        }
                    })
                };
                for width in [2, 1, 0] {
                    let member = match width {
                        2 => {
                            fold(self.u.get(at)) == Some(0x61)
                                && fold(self.u.get(at + 1)) == Some(0x62)
                        }
                        1 => fold(self.u.get(at)) == Some(0x61),
                        _ => self.nullable,
                    };
                    if !member || (width == 0 && count >= self.minimum) {
                        continue;
                    }
                    if let Some(found) = self.visit(at + width, count + 1, Some(at..at + width)) {
                        return Some(found);
                    }
                }
            }
            if !self.lazy && count >= self.minimum && self.end(at) {
                Some((at, last))
            } else {
                None
            }
        }
    }
    for (k, (left, right, left_flags, right_flags)) in profiles.into_iter().enumerate() {
        let (after_left, after_right, after_lf, after_rf) = profiles[(k + 3) % profiles.len()];
        for (q, minimum, maximum, lazy) in [
            ("", 1, Some(1), false),
            ("{1}", 1, Some(1), false),
            ("{1,1}?", 1, Some(1), false),
            ("{0001,0001}", 1, Some(1), false),
        ] {
            for nullable in [false, true] {
                for outside in ["", "{2,3}?", "{99999999999999999999999999}", "?", "{0,2}?"] {
                    let class = if nullable {
                        r"[\q{|a|ab}]"
                    } else {
                        r"[\q{a|ab}]"
                    };
                    let source = format!(
                        "(({left})|({right})){outside}({class}){q}(({after_left})|({after_right})){outside}"
                    );
                    for (i, m) in [(false, false), (true, false), (false, true), (true, true)] {
                        let plan =
                            P::compile_with_work(&JsString::from(source.as_str()), i, m, |_| {
                                Ok::<(), ()>(())
                            })
                            .unwrap()
                            .unwrap_or_else(|| panic!("declined {source}"));
                        assert_eq!(plan.capture_count(), 7);
                        for text in [
                            "",
                            "a",
                            "ab",
                            "aba",
                            "aab!",
                            "!ab",
                            "AB",
                            "\na\n",
                            "ſab!",
                            "😀a",
                            "\u{2028}ab\u{2029}",
                        ] {
                            let input = JsString::from(text);
                            let u = input.code_units();
                            let skip = matches!(outside, "?" | "{0,2}?");
                            let oracle = Ref {
                                u,
                                i,
                                m,
                                minimum,
                                maximum: maximum.unwrap_or(u.len() + minimum + 1),
                                lazy,
                                nullable,
                                after: [after_lf, after_rf],
                                skip,
                            };
                            for requested in 0..=u.len() + 1 {
                                for sticky in [false, true] {
                                    let mut at = requested;
                                    if at > 0
                                        && at < u.len()
                                        && (0xdc00..=0xdfff).contains(&u[at])
                                        && (0xd800..=0xdbff).contains(&u[at - 1])
                                    {
                                        at -= 1;
                                    }
                                    let mut expected = None;
                                    while at <= u.len() {
                                        if skip
                                            || oracle.predicate(at, left_flags)
                                            || oracle.predicate(at, right_flags)
                                        {
                                            if let Some((end, last)) = oracle.visit(at, 0, None) {
                                                expected = Some((at..end, last));
                                                break;
                                            }
                                        }
                                        if sticky || at == u.len() {
                                            break;
                                        }
                                        at += if (0xd800..=0xdbff).contains(&u[at])
                                            && u.get(at + 1)
                                                .is_some_and(|p| (0xdc00..=0xdfff).contains(p))
                                        {
                                            2
                                        } else {
                                            1
                                        };
                                    }
                                    let found = plan
                                        .find_with_captures_and_work(
                                            &input,
                                            requested,
                                            sticky,
                                            |_| Ok::<(), ()>(()),
                                        )
                                        .unwrap();
                                    assert_eq!(
                                        found.as_ref().map(|f| (
                                            f.repeated.range.clone(),
                                            f.repeated.last_iteration.clone()
                                        )),
                                        expected,
                                        "{source}, {text:?}, {requested}, {sticky}, {i}, {m}"
                                    );
                                    if let Some(f) = found {
                                        let a = f.repeated.range.start;
                                        let b = f.repeated.range.end;
                                        let mut want = vec![None; 7];
                                        want[3] = f.repeated.last_iteration.clone();
                                        if !skip {
                                            want[0] = Some(a..a);
                                            want[if oracle.predicate(a, left_flags) {
                                                1
                                            } else {
                                                2
                                            }] = Some(a..a);
                                            want[4] = Some(b..b);
                                            want[if oracle.predicate(b, after_lf) {
                                                5
                                            } else {
                                                6
                                            }] = Some(b..b);
                                        }
                                        assert_eq!(
                                            (0..7)
                                                .map(|n| plan.capture_range(n, &f))
                                                .collect::<Vec<_>>(),
                                            want,
                                            "{source}, {text:?}, {requested}"
                                        );
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
#[test]
fn conjunctive_predicate_choice_single_classes_keep_deep_required_scopes_and_endpoint_retry_flat() {
    use crate::RegExpUnicodeConjunctivePredicateChoiceSingleStringClassCaptureMatcher as P;
    let source = JsString::from(
        format!(
            r"{}((\b^)|(^)){}([\q{{a|ab}}])",
            "(".repeat(20_000),
            ")".repeat(20_000)
        )
        .as_str(),
    );
    let plan = P::compile_with_work(&source, false, false, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    assert_eq!(plan.capture_count(), 20_004);
    let found = plan
        .find_with_captures_and_work(&JsString::from("ab"), 0, true, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    assert_eq!(found.repeated.range, 0..2);
    assert_eq!(plan.capture_range(0, &found), Some(0..0));
    assert_eq!(plan.capture_range(20_001, &found), Some(0..0));
    assert_eq!(plan.capture_range(20_002, &found), None);
    assert_eq!(plan.capture_range(20_003, &found), Some(0..2));
    let clone = plan.clone();
    drop(plan);
    assert_eq!(clone.capture_range(20_003, &found), Some(0..2));
    let plan = P::compile_with_work(
        &JsString::from(r"^((\b)|(\b))([\q{ab!|a|X|!}])((\B)|(\b\B))"),
        false,
        false,
        |_| Ok::<(), ()>(()),
    )
    .unwrap()
    .unwrap();
    let found = plan
        .find_with_captures_and_work(&JsString::from("ab!Xc"), 0, true, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    assert_eq!(found.repeated.range, 0..1);
    assert_eq!(plan.capture_range(3, &found), Some(0..1));
    assert_eq!(plan.capture_range(5, &found), Some(1..1));
    assert_eq!(plan.capture_range(6, &found), None);
    let word = "a".repeat(20_000);
    let source = JsString::from(format!(r"((\b^)|(^))([\q{{{word}|a}}])((\b$)|($))").as_str());
    let plan = P::compile_with_work(&source, false, false, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    let found =
        plan.find_with_captures_and_work(&JsString::from(word.as_str()), 0, true, |_| {
            Ok::<(), ()>(())
        })
        .unwrap()
        .unwrap();
    assert_eq!(found.repeated.range, 0..20_000);
    assert_eq!(plan.capture_range(3, &found), Some(0..20_000));
    assert_eq!(plan.capture_range(5, &found), Some(20_000..20_000));
}
#[test]
fn conjunctive_predicate_choice_single_classes_charge_cancellation_and_keep_nonconjunctions_unproved()
 {
    use crate::{
        RegExpUnicodeConjunctivePredicateChoiceSingleStringClassCaptureMatcher as P,
        RegExpUnicodeMatchError, RegExpUnicodeSetCompileError,
    };
    for source in [
        r"((\b^)|(^))([\q{a|ab}])((\b$)|($))",
        r"((\b)|(\b))(([\q{|a|ab}])){1}((\B)|(\b\B))",
        r"((\b\B)|(\b\B))([\p{Any}\q{|ab}])",
        r"((\b)|(\b))([\q{ab}&&\q{cd}])((\B)|(\B))",
    ] {
        let source = JsString::from(source);
        let mut calls = 0;
        let plan = P::compile_with_work(&source, false, true, |_| {
            calls += 1;
            Ok::<(), usize>(())
        })
        .unwrap()
        .unwrap();
        for stop in 0..calls {
            let mut n = 0;
            let result = P::compile_with_work(&source, false, true, |_| {
                let call = n;
                n += 1;
                if call == stop { Err(call) } else { Ok(()) }
            });
            assert!(matches!(result,Err(RegExpUnicodeSetCompileError::Work(n)) if n==stop));
        }
        for text in ["ab!\n", "", "😀a"] {
            let input = JsString::from(text);
            let mut calls = 0;
            let expected = plan
                .find_with_captures_and_work(&input, 0, false, |_| {
                    calls += 1;
                    Ok::<(), usize>(())
                })
                .unwrap();
            for stop in 0..calls {
                let mut n = 0;
                let result = plan.find_with_captures_and_work(&input, 0, false, |_| {
                    let call = n;
                    n += 1;
                    if call == stop { Err(call) } else { Ok(()) }
                });
                assert!(matches!(result,Err(RegExpUnicodeMatchError::Work(n)) if n==stop));
                assert_eq!(
                    plan.find_with_captures_and_work(&input, 0, false, |_| Ok::<(), usize>(()))
                        .unwrap(),
                    expected
                );
            }
        }
    }
    for source in [
        r"(^|\b)([\q{a|ab}])",
        r"($|\b)([\q{a|ab}])",
        r"(^|$)([\q{a|ab}])",
        r"((\b)|z|())([\q{a|ab}])",
        r"((\b)|\1|())([\q{a|ab}])",
        r"((\b\B)|(\b\B))(()|([\q{ab}&&\p{RGI_Emoji}]))+",
        r"((\b)|(\b))([\q{a|ab}])[a]",
        r"((\b)|(\b))([\q{a|ab}]){2}",
        r"((\b)|(\b))([\q{a|ab}])|()",
    ] {
        assert!(
            P::compile_with_work(&JsString::from(source), false, false, |_| Ok::<(), ()>(()))
                .unwrap()
                .is_none(),
            "{source}"
        );
    }
}
