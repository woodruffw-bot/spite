#[test]
fn predicate_choice_alternatives_preserve_independent_class_empty_order_and_endpoint_masks() {
    use crate::RegExpUnicodePredicateChoiceStringClassAlternativeMatcher as P;
    for (class, nullable, scalar, never) in [
        (r"[\q{a|ab}]", false, false, false),
        (r"[\q{|a|ab}]", true, false, false),
        (r"[\p{Any}\q{|ab}]", true, true, false),
        (r"[\q{ab}&&\q{cd}]", false, false, true),
    ] {
        for empty_first in [false, true] {
            for class_count in ["", "{1}", "{0001,0001}?"] {
                for choice_count in ["", "{1,1}?"] {
                    for outside in [
                        "",
                        "{3}",
                        "{99999999999999999999999999999999}",
                        "?",
                        "{0,2}?",
                    ] {
                        let body = if empty_first {
                            format!("(()|({class}){class_count}){choice_count}")
                        } else {
                            format!("(({class}){class_count}|()){choice_count}")
                        };
                        let source =
                            format!(r"((\b)|(\B)){outside}{body}((^)|($)|(\b)|(\B)){outside}");
                        for (i, m) in [(false, false), (true, false), (false, true), (true, true)] {
                            let plan = P::compile_with_work(
                                &JsString::from(source.as_str()),
                                i,
                                m,
                                |_| Ok::<(), ()>(()),
                            )
                            .unwrap()
                            .unwrap_or_else(|| panic!("declined {source}"));
                            assert_eq!(plan.capture_count(), 11);
                            for text in [
                                "",
                                "a",
                                "ab",
                                "aba",
                                "!ab!",
                                "ſaX",
                                "😀a",
                                "a\n",
                                "\u{2028}ab\u{2029}",
                            ] {
                                let input = JsString::from(text);
                                let u = input.code_units();
                                let truth = |at: usize| {
                                    let word = |p: Option<&u16>| {
                                        p.is_some_and(|p| {
                                            matches!(*p,0x30..=0x39|0x41..=0x5a|0x5f|0x61..=0x7a)
                                                || (i && matches!(*p, 0x17f | 0x212a))
                                        })
                                    };
                                    [
                                        at == 0
                                            || (m
                                                && matches!(
                                                    u[at - 1],
                                                    0x0a | 0x0d | 0x2028 | 0x2029
                                                )),
                                        at == u.len()
                                            || (m
                                                && matches!(u[at], 0x0a | 0x0d | 0x2028 | 0x2029)),
                                        word(at.checked_sub(1).and_then(|p| u.get(p)))
                                            != word(u.get(at)),
                                    ]
                                };
                                for requested in 0..=input.len() + 1 {
                                    for sticky in [false, true] {
                                        let found = plan
                                            .find_with_captures_and_work(
                                                &input,
                                                requested,
                                                sticky,
                                                |_| Ok::<(), ()>(()),
                                            )
                                            .unwrap();
                                        if requested > u.len() {
                                            assert!(found.is_none());
                                            continue;
                                        }
                                        let mut at = requested;
                                        if at > 0
                                            && at < u.len()
                                            && (0xdc00..=0xdfff).contains(&u[at])
                                            && (0xd800..=0xdbff).contains(&u[at - 1])
                                        {
                                            at -= 1;
                                        }
                                        let width = if never {
                                            None
                                        } else if u.get(at..at + 2) == Some(&[0x61, 0x62]) {
                                            Some(2)
                                        } else if u.get(at) == Some(&0x61) {
                                            Some(1)
                                        } else if scalar && at < u.len() {
                                            Some(
                                                if (0xd800..=0xdbff).contains(&u[at])
                                                    && u.get(at + 1).is_some_and(|p| {
                                                        (0xdc00..=0xdfff).contains(p)
                                                    })
                                                {
                                                    2
                                                } else {
                                                    1
                                                },
                                            )
                                        } else if nullable {
                                            Some(0)
                                        } else {
                                            None
                                        };
                                        let selected = !empty_first && width.is_some();
                                        let end = at + if selected { width.unwrap() } else { 0 };
                                        let range = at..end;
                                        let f = found.unwrap();
                                        assert_eq!(
                                            f.repeated.range, range,
                                            "{source}, {text:?}, {requested}"
                                        );
                                        assert_eq!(f.repeated.class_selected, selected);
                                        let mut want = vec![None; 11];
                                        want[3] = Some(range.clone());
                                        want[if empty_first || selected { 4 } else { 5 }] =
                                            Some(if selected { range } else { at..at });
                                        if !matches!(outside, "?" | "{0,2}?") {
                                            let a = truth(at);
                                            let b = truth(end);
                                            want[0] = Some(at..at);
                                            want[if a[2] { 1 } else { 2 }] = Some(at..at);
                                            want[6] = Some(end..end);
                                            want[if b[0] {
                                                7
                                            } else if b[1] {
                                                8
                                            } else if b[2] {
                                                9
                                            } else {
                                                10
                                            }] = Some(end..end);
                                        }
                                        assert_eq!(
                                            (0..11)
                                                .map(|n| plan.capture_range(n, &f))
                                                .collect::<Vec<_>>(),
                                            want,
                                            "{source}, {text:?}, {requested}, {sticky}, {i}, {m}"
                                        );
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
#[test]
fn predicate_choice_alternatives_keep_deep_mandatory_scopes_and_empty_identity_flat() {
    use crate::RegExpUnicodePredicateChoiceStringClassAlternativeMatcher as P;
    for suffix in ["", "?"] {
        let source = JsString::from(
            format!(
                r"{}((\b)|(\B)){}(([\q{{}}])|())",
                "(".repeat(20_000),
                format!("){suffix}").repeat(20_000)
            )
            .as_str(),
        );
        let plan = P::compile_with_work(&source, false, false, |_| Ok::<(), ()>(()))
            .unwrap()
            .unwrap();
        assert_eq!(plan.capture_count(), 20_006);
        let found = plan
            .find_with_captures_and_work(&JsString::from(""), 0, true, |_| Ok::<(), ()>(()))
            .unwrap()
            .unwrap();
        assert_eq!(found.repeated.range, 0..0);
        assert!(found.repeated.class_selected);
        assert_eq!(
            plan.capture_range(0, &found),
            if suffix.is_empty() { Some(0..0) } else { None }
        );
        assert_eq!(plan.capture_range(20_001, &found), None);
        assert_eq!(
            plan.capture_range(20_002, &found),
            if suffix.is_empty() { Some(0..0) } else { None }
        );
        assert_eq!(plan.capture_range(20_003, &found), Some(0..0));
        assert_eq!(plan.capture_range(20_004, &found), Some(0..0));
        assert_eq!(plan.capture_range(20_005, &found), None);
        let clone = plan.clone();
        drop(plan);
        assert_eq!(clone.capture_range(20_004, &found), Some(0..0));
        let forged = crate::RegExpUnicodePredicateChoiceStringClassMatch {
            before: 255,
            after: 255,
            ..found
        };
        assert_eq!(clone.capture_range(0, &forged), None);
    }
    let plan = P::compile_with_work(
        &JsString::from(r"^((\b)|(\B))(([\q{ab!|a|X|!}])|())\B"),
        false,
        false,
        |_| Ok::<(), ()>(()),
    )
    .unwrap()
    .unwrap();
    let found = plan
        .find_with_captures_and_work(&JsString::from("ab!Xc"), 0, false, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    assert_eq!(found.repeated.range, 0..1);
    assert!(found.repeated.class_selected);
    assert_eq!(plan.capture_range(4, &found), Some(0..1));
    let word = "a".repeat(20_000);
    let source = JsString::from(format!(r"^((\b)|(\B))(()|([\q{{{word}|a}}]))((^)|())$").as_str());
    let plan = P::compile_with_work(&source, false, false, |_| Ok::<(), ()>(()))
        .unwrap()
        .unwrap();
    let found =
        plan.find_with_captures_and_work(&JsString::from(word.as_str()), 0, true, |_| {
            Ok::<(), ()>(())
        })
        .unwrap()
        .unwrap();
    assert_eq!(found.repeated.range, 0..20_000);
    assert!(found.repeated.class_selected);
    assert_eq!(plan.capture_range(5, &found), Some(0..20_000));
    assert_eq!(plan.capture_range(4, &found), None);
}
#[test]
fn predicate_choice_alternatives_charge_cancellation_and_decline_branch_local_overlays() {
    use crate::{
        RegExpUnicodeMatchError, RegExpUnicodePredicateChoiceStringClassAlternativeMatcher as P,
        RegExpUnicodeSetCompileError,
    };
    for source in [
        r"((\b)|(\B))(([\q{a|ab}])|())((^)|())",
        r"^((^)|())(()|([\q{|a|ab}]))((\b)|(\B))$",
        r"((\b)|(\B))(([\p{Any}\q{|ab}])|()){1}((^)|())",
        r"((\b)|(\B))(([\q{ab}&&\q{cd}])|())",
    ] {
        let source = JsString::from(source);
        let mut calls = 0;
        let plan = P::compile_with_work(&source, false, true, |_| {
            calls += 1;
            Ok::<(), usize>(())
        })
        .unwrap()
        .unwrap();
        for stop in 0..calls {
            let mut n = 0;
            let result = P::compile_with_work(&source, false, true, |_| {
                let call = n;
                n += 1;
                if call == stop { Err(call) } else { Ok(()) }
            });
            assert!(matches!(result,Err(RegExpUnicodeSetCompileError::Work(n)) if n==stop));
        }
        for text in ["ab!\n", "", "😀a"] {
            let input = JsString::from(text);
            let mut calls = 0;
            let expected = plan
                .find_with_captures_and_work(&input, 0, false, |_| {
                    calls += 1;
                    Ok::<(), usize>(())
                })
                .unwrap();
            for stop in 0..calls {
                let mut n = 0;
                let result = plan.find_with_captures_and_work(&input, 0, false, |_| {
                    let call = n;
                    n += 1;
                    if call == stop { Err(call) } else { Ok(()) }
                });
                assert!(matches!(result,Err(RegExpUnicodeMatchError::Work(n)) if n==stop));
                assert_eq!(
                    plan.find_with_captures_and_work(&input, 0, false, |_| Ok::<(), usize>(()))
                        .unwrap(),
                    expected
                );
            }
        }
    }
    for source in [
        r"(([\q{a|ab}])|())",
        r"((\b)|(\B))([\q{a|ab}])+",
        r"((\b)|z|())(([\q{a|ab}])|())",
        r"((\b)|\1|())(([\q{a|ab}])|())",
        r"((\b)|(\B))(()|([\q{ab}&&\p{RGI_Emoji}]))",
        r"((\b)|(\B))(([\q{a|ab}])|())[a]",
        r"((\b)|(\B))(([\q{a|ab}])|()){2}",
        r"(((\b)|(\B))([\q{a|ab}]))|()",
        r"((\b)|(\B))(((\b)|(\B))([\q{a|ab}])|())",
    ] {
        assert!(
            P::compile_with_work(&JsString::from(source), false, false, |_| Ok::<(), ()>(()))
                .unwrap()
                .is_none(),
            "{source}"
        );
    }
}
